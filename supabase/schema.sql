create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  study_level text default 'Quero aprender desde o básico',
  created_at timestamptz not null default now()
);

create table if not exists public.lesson_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_slug text not null,
  completed boolean not null default false,
  score integer check (score >= 0 and score <= 100),
  updated_at timestamptz not null default now(),
  unique (user_id, lesson_slug)
);

create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  quiz_slug text not null,
  score integer not null check (score >= 0 and score <= 100),
  answers jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.lesson_progress enable row level security;
alter table public.quiz_attempts enable row level security;

create policy "profile read own" on public.profiles for select using (auth.uid() = id);
create policy "profile insert own" on public.profiles for insert with check (auth.uid() = id);
create policy "profile update own" on public.profiles for update using (auth.uid() = id);

create policy "progress read own" on public.lesson_progress for select using (auth.uid() = user_id);
create policy "progress insert own" on public.lesson_progress for insert with check (auth.uid() = user_id);
create policy "progress update own" on public.lesson_progress for update using (auth.uid() = user_id);

create policy "quiz read own" on public.quiz_attempts for select using (auth.uid() = user_id);
create policy "quiz insert own" on public.quiz_attempts for insert with check (auth.uid() = user_id);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, full_name, study_level)
  values (new.id, new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'study_level')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();
